-- Создаем пользователя root с правами суперпользователя для внешних подключений
-- Это выполнится только при первой инициализации контейнера

-- PostgreSQL автоматически создает пользователя из POSTGRES_USER (root) и базу данных из POSTGRES_DB (db)
-- Убеждаемся, что у пользователя root есть все необходимые права

-- Предоставляем все права на базу данных
GRANT ALL PRIVILEGES ON DATABASE db TO root;
